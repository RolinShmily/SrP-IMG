"""Data emitters for the Worker runtime: ``worker/targets.js`` + ``worker/slot_formats.js``.

The runtime policy is hand-written JavaScript in ``worker/``; this module only
serialises the category data that changes when the image pool changes. Nothing
here emits executable logic, so both modules can be reviewed as data.

The byte layout is part of the output contract: ``HASH_LENGTH``/``IMAGE_EXT``
as literals and ``TARGETS``/``SLOT_FORMATS`` double-encoded through
``JSON.parse``. Keep the ``json.dumps`` nesting identical to the pre-P2 emitter
— ``worker/targets.js`` must stay byte-for-byte reproducible.
"""
import json
from pathlib import Path
from typing import List, Optional, Union

from .catalog import load_catalog
from .config import Config
from .models import CategoryResult

HEADER = "// Generated by `python -m pipeline`. Do not edit.\n"

#: Written next to ``targets.js`` (always in the same ``worker/`` directory).
SLOT_FORMATS_NAME = "slot_formats.js"


def build_targets(config: Config, meta: dict, results: Optional[List[CategoryResult]] = None) -> dict:
    counts = meta.get('counts', {})
    category_exts = meta.get('category_exts', {})
    ext = meta.get('output_ext', config.default_ext)

    label_lookup = {r.name: r.label for r in results or []}
    # Catalog labels are the fallback for callers that only pass metadata;
    # unknown categories resolve to their own key, matching the old map.
    catalog = load_catalog(config.catalog_path)
    return {
        cat: {
            'dir': cat,
            'slots': counts[cat],
            'ext': category_exts.get(cat, ext),
            'label': label_lookup.get(cat, catalog.get(cat).label),
        }
        for cat in sorted(counts)
    }


def render_targets(config: Config, meta: dict, results: Optional[List[CategoryResult]] = None) -> str:
    hl = meta.get('hash_length', config.hash_length)
    ext = meta.get('output_ext', config.default_ext)
    targets = build_targets(config, meta, results)
    return (
        HEADER
        + f"export const HASH_LENGTH = {hl};\n"
        + f"export const IMAGE_EXT = {json.dumps(ext)};\n"
        + f"export const TARGETS = JSON.parse({json.dumps(json.dumps(targets, ensure_ascii=True))});\n"
    )


def build_slot_formats(meta: dict, results: Optional[List[CategoryResult]] = None) -> dict:
    """Category -> one format code per slot, in slot order.

    Categories come from the manifest's ``counts`` (the same canonical, sorted
    key set as ``TARGETS``); a category without a result keeps an empty string,
    which matches a zero-slot category.
    """
    counts = meta.get('counts', {})
    by_name = {r.name: ''.join(r.slot_formats) for r in results or []}
    return {cat: by_name.get(cat, '') for cat in sorted(counts)}


def render_slot_formats(
    meta: dict,
    results: Optional[List[CategoryResult]] = None,
) -> str:
    formats = build_slot_formats(meta, results)
    return (
        HEADER
        + "export const SLOT_FORMATS = JSON.parse("
        + json.dumps(json.dumps(formats, ensure_ascii=True))
        + ");\n"
    )


def write_slot_formats(
    config: Config,
    meta: dict,
    results: Optional[List[CategoryResult]] = None,
    path: Union[str, Path, None] = None,
) -> Path:
    target = Path(path) if path is not None else config.targets_path.parent / SLOT_FORMATS_NAME
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render_slot_formats(meta, results))
    print(f"Wrote {target}")
    return target


def write_targets(
    config: Config,
    meta: dict,
    results: Optional[List[CategoryResult]] = None,
    path: Union[str, Path, None] = None,
) -> Path:
    target = Path(path) if path is not None else config.targets_path
    target.parent.mkdir(parents=True, exist_ok=True)
    with open(target, 'w', encoding='utf-8', newline='\n') as f:
        f.write(render_targets(config, meta, results))
    print(f"Wrote {target}")
    # Emitted together with the targets: both describe the same pool, and a
    # half-updated pair would serve the wrong MIME types on every request.
    write_slot_formats(config, meta, results, path=target.parent / SLOT_FORMATS_NAME)
    return target
